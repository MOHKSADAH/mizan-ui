import { directions, fontStack } from '../lib/directions';

// The docs site loads fonts through next/font: real family names first (Google's name, without Fontsource's " Variable"), then the loader variables.
const docs = (pair: { latin: string; arabic: string }) =>
  fontStack(pair, (f) => `"${f.family.replace(/ Variable$/, '')}"`, (f) => `var(${f.variable})`);

const css = directions
  .map(
    (d) => `[data-font='${d.id}'] {
  --font-body: ${docs(d.body)};
  --font-display: ${docs(d.display)};
  --font-code: ${docs({ latin: d.code, arabic: d.code })};
  --tracking-heading: ${d.tracking};
}
`,
  )
  .join('');

await Bun.write('app/directions.css', `/* Generated by scripts/build-directions.ts from scripts/data/directions.json. Do not edit. */\n${css}`);
console.log(`directions: ${directions.length}`);
