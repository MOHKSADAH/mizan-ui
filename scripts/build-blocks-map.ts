import { manifest } from '../registry/manifest';

// Writes the client import map for block previews. A template import() over an empty folder breaks the bundler.
const blocks = manifest.filter((i) => i.type === 'registry:block');
const lines = blocks.map((b) => `  '${b.name}': () => import('@/${b.files[0].replace(/\.tsx$/, '')}'),`);
const out = `// Generated by scripts/build-blocks-map.ts from the registry manifest. Do not edit.
export const blockLoaders: Record<string, () => Promise<unknown>> = {
${lines.join('\n')}
};
`;
await Bun.write('components/blocks/loaders.ts', out);
console.log(`block loaders: ${blocks.length}`);
