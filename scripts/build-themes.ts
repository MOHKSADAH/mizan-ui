import { mkdir, readdir, rm } from 'node:fs/promises';
import { SERIES } from '../registry/base/series';

type Tokens = Record<string, string>;
type Source = {
  id: string;
  name: string;
  source: 'mizan' | 'shadcn' | 'tweakcn';
  kind: string;
  light: Tokens;
  dark: Tokens;
  radius?: string;
  font?: string;
  weight?: string;
  extras?: { light?: Tokens; dark?: Tokens };
};

export type ThemeGroup = 'mizan' | 'shadcn-base' | 'shadcn-accent' | 'tweakcn';
export type ThemeTokens = { light: Tokens; dark: Tokens };

const EXTRA_VARS: Record<string, string> = {
  'shadow-color': 'shadow-color',
  'shadow-opacity': 'shadow-opacity',
  'shadow-blur': 'shadow-blur',
  'shadow-spread': 'shadow-spread',
  'shadow-offset-x': 'shadow-x',
  'shadow-offset-y': 'shadow-y',
  'letter-spacing': 'tracking-normal',
  spacing: 'spacing',
};

const groupOf = (t: Source): ThemeGroup =>
  t.source === 'mizan' ? 'mizan' : t.source === 'tweakcn' ? 'tweakcn' : t.kind === 'accent' ? 'shadcn-accent' : 'shadcn-base';

function mizanFill(tokens: Tokens, mode: 'light' | 'dark'): Tokens {
  const out = { ...tokens };
  SERIES[mode].forEach((c, i) => (out[`chart-${i + 1}`] = c));
  for (const k of ['primary', 'primary-foreground', 'accent', 'accent-foreground', 'border', 'ring'])
    out[`sidebar-${k}`] = tokens[k];
  out.sidebar = tokens.background;
  out['sidebar-foreground'] = tokens.foreground;
  return out;
}

const extrasOf = (t: Source, mode: 'light' | 'dark'): Tokens => {
  const merged = { ...t.extras?.light, ...(mode === 'dark' ? t.extras?.dark : {}) };
  return Object.fromEntries(Object.entries(merged).flatMap(([k, v]) => (EXTRA_VARS[k] ? [[EXTRA_VARS[k], v]] : [])));
};

export function resolve(t: Source, tweakcnDefaults: ThemeTokens): ThemeTokens {
  if (t.source === 'mizan') return { light: mizanFill(t.light, 'light'), dark: mizanFill(t.dark, 'dark') };
  if (t.source === 'tweakcn')
    return {
      light: { ...tweakcnDefaults.light, ...t.light, ...extrasOf(t, 'light') },
      dark: { ...tweakcnDefaults.dark, ...t.light, ...t.dark, ...extrasOf(t, 'dark') },
    };
  return { light: t.light, dark: t.dark };
}

const COLOR_KEYS = new Set([
  'background', 'foreground', 'card', 'card-foreground', 'popover', 'popover-foreground', 'primary',
  'primary-foreground', 'secondary', 'secondary-foreground', 'muted', 'muted-foreground', 'accent',
  'accent-foreground', 'destructive', 'border', 'input', 'ring', 'chart-1', 'chart-2', 'chart-3', 'chart-4',
  'chart-5', 'sidebar', 'sidebar-foreground', 'sidebar-primary', 'sidebar-primary-foreground', 'sidebar-accent',
  'sidebar-accent-foreground', 'sidebar-border', 'sidebar-ring',
  ...Object.values(EXTRA_VARS),
]);

// destructive-foreground stays Mizan-defined (tokens.css), so it is not taken from a theme.
const pick = (tokens: Tokens) => Object.fromEntries(Object.entries(tokens).filter(([k]) => COLOR_KEYS.has(k)));

const block = (selector: string, tokens: Tokens) =>
  `${selector} {\n${Object.entries(tokens)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join('\n')}\n}\n`;

export function themeCss(id: string, tokens: ThemeTokens, radius?: string) {
  const root = id === 'mizan-base' ? `:root, :root[data-theme='${id}']` : `:root[data-theme='${id}']`;
  const dark = id === 'mizan-base' ? `:root.dark, :root[data-theme='${id}'].dark` : `:root[data-theme='${id}'].dark`;
  return (
    `/* Generated by scripts/build-themes.ts from scripts/data/themes.json. Do not edit. */\n` +
    block(root, { ...(radius && { radius }), ...pick(tokens.light) }) +
    block(dark, pick(tokens.dark))
  );
}

const seriesCss = () =>
  `/* Generated by scripts/build-themes.ts from registry/base/series.ts. Do not edit. */\n` +
  ([[':root', 'light'], [':root.dark', 'dark']] as const)
    .map(
      ([selector, mode]) =>
        `${selector} {\n${SERIES[mode].map((c, i) => `  --series-${i + 1}: var(--chart-${i + 1}, ${c});`).join('\n')}\n}\n`,
    )
    .join('\n');

if (import.meta.main) {
  const data = (await Bun.file('scripts/data/themes.json').json()) as {
    tweakcnDefaults: ThemeTokens;
    themes: Source[];
  };
  await mkdir('registry/themes', { recursive: true });
  // Remove stale files only: deleting the folder would break a running dev server.
  const keep = new Set(['index.css', ...data.themes.map((t) => `${t.id}.css`)]);
  for (const f of await readdir('registry/themes')) if (!keep.has(f)) await rm(`registry/themes/${f}`);
  const index = [];
  const all: Record<string, ThemeTokens & { radius?: string }> = {};
  for (const t of data.themes) {
    const tokens = resolve(t, data.tweakcnDefaults);
    const radius = t.radius ?? tokens.light.radius;
    await Bun.write(`registry/themes/${t.id}.css`, themeCss(t.id, tokens, radius));
    all[t.id] = { light: pick(tokens.light), dark: pick(tokens.dark), ...(radius && { radius }) };
    const sw = (m: Tokens) => [m.primary, m.secondary, m.background];
    index.push({
      id: t.id,
      name: t.name,
      group: groupOf(t),
      font: t.font ?? 'geist',
      weight: t.weight ?? 'regular',
      swatches: { light: sw(tokens.light), dark: sw(tokens.dark) },
    });
  }
  await Bun.write(
    'registry/themes/index.css',
    `/* Generated by scripts/build-themes.ts. Do not edit. */\n${data.themes.map((t) => `@import './${t.id}.css';`).join('\n')}\n`,
  );
  await Bun.write('registry/base/series.css', seriesCss());
  await Bun.write('lib/themes/index.json', JSON.stringify(index) + '\n');
  await Bun.write('lib/themes/tokens.json', JSON.stringify(all) + '\n');
  console.log(`themes: ${data.themes.length}`);
}
