'use client';

import * as React from 'react';
import { flushSync } from 'react-dom';
import { useTheme } from 'next-themes';
import { SERIES } from '@/registry/base/series';
import { seriesPass, toRgb } from '@/lib/contrast';
import aa from '@/lib/themes/aa.json';
import {
  applySettings,
  defaultSettings,
  STORAGE_KEY,
  themeById,
  themeFonts,
  TUNE_VARS,
  type IconWeight,
  type Settings,
} from '@/lib/settings';
import { useReducedMotion } from '@/components/use-reduced-motion';

type Mode = 'light' | 'dark';
type Checks = { aaFailures: string[]; seriesFallback: boolean };

// Failing AA pairs per theme and mode, generated by scripts/build-aa.ts.
export const aaOf = (themeId: string, mode: Mode) =>
  (aa as Record<string, Record<Mode, string[]>>)[themeId]?.[mode] ?? [];

type SettingsContext = Settings & {
  update: (patch: Partial<Settings>) => void;
  reset: () => void;
  iconWeight: IconWeight;
  checks: Checks;
};

const Context = React.createContext<SettingsContext | null>(null);

export function useSettings() {
  const ctx = React.useContext(Context);
  if (!ctx) throw new Error('useSettings must be used inside SettingsProvider');
  return ctx;
}

// Settings live in localStorage; this store lets React read them without an effect.
const EVENT = 'mizan-settings';
let raw: string | null = null;

function readRaw() {
  if (raw === null) {
    try {
      raw = localStorage.getItem(STORAGE_KEY) ?? '';
    } catch {
      raw = '';
    }
  }
  return raw;
}

function subscribe(onChange: () => void) {
  const onStorage = (e: StorageEvent) => {
    if (e.key !== STORAGE_KEY) return;
    raw = null;
    onChange();
  };
  window.addEventListener(EVENT, onChange);
  window.addEventListener('storage', onStorage);
  return () => {
    window.removeEventListener(EVENT, onChange);
    window.removeEventListener('storage', onStorage);
  };
}

function parseSettings(json: string): Settings {
  try {
    return { ...defaultSettings, ...JSON.parse(json || '{}') };
  } catch {
    return defaultSettings;
  }
}

// Runs a DOM change inside a view transition when the browser supports it and motion is allowed.
export function withViewTransition(change: () => void, reduced: boolean) {
  if (reduced || !document.startViewTransition) return change();
  document.startViewTransition(() => flushSync(change));
}

export function SettingsProvider({ children }: { children: React.ReactNode }) {
  const stored = React.useSyncExternalStore(subscribe, readRaw, () => '');
  const settings = React.useMemo(() => parseSettings(stored), [stored]);
  const [seriesFallback, setSeriesFallback] = React.useState(false);
  const { resolvedTheme } = useTheme();
  const mode: Mode = resolvedTheme === 'dark' ? 'dark' : 'light';
  const reduced = useReducedMotion();

  const update = React.useCallback(
    (patch: Partial<Settings>) => {
      const next = { ...settings, ...patch };
      withViewTransition(
        () => {
          raw = JSON.stringify(next);
          try {
            localStorage.setItem(STORAGE_KEY, raw);
          } catch {}
          applySettings(next, themeFonts, TUNE_VARS);
          window.dispatchEvent(new Event(EVENT));
        },
        reduced || !('theme' in patch || 'font' in patch || 'weight' in patch),
      );
    },
    [settings, reduced],
  );

  const reset = React.useCallback(() => update({ font: 'auto', weight: 'auto', tune: {} }), [update]);

  // Contrast guard: swap in the validated series palette when the theme's chart colors fail on the card.
  React.useEffect(() => {
    const frame = requestAnimationFrame(() => {
      const root = document.documentElement;
      const current = root.classList.contains('dark') ? 'dark' : 'light';
      for (let i = 1; i <= 5; i++) root.style.removeProperty(`--series-${i}`);
      const css = getComputedStyle(root);
      const get = (token: string) => toRgb(css.getPropertyValue(`--${token}`).trim());
      const fallback = !seriesPass([1, 2, 3, 4, 5].map((i) => get(`series-${i}`)), get('card'));
      if (fallback) SERIES[current].forEach((c, i) => root.style.setProperty(`--series-${i + 1}`, c));
      setSeriesFallback(fallback);
    });
    return () => cancelAnimationFrame(frame);
  }, [settings.theme, resolvedTheme]);

  const theme = themeById[settings.theme] ?? themeById['mizan-base'];
  const iconWeight = (settings.weight === 'auto' ? theme.weight : settings.weight) as IconWeight;

  const checks = React.useMemo(
    () => ({ aaFailures: aaOf(settings.theme, mode), seriesFallback }),
    [settings.theme, mode, seriesFallback],
  );

  const value = React.useMemo(
    () => ({ ...settings, update, reset, iconWeight, checks }),
    [settings, update, reset, iconWeight, checks],
  );
  return <Context.Provider value={value}>{children}</Context.Provider>;
}
